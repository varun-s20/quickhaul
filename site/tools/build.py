def read(*parts):
    path = os.path.join(*parts)
    if not os.path.exists(path):
        sys.exit('Missing file: ' + os.path.relpath(path, ROOT))
    with open(path, encoding='utf-8') as fh:
        return fh.read()


def esc(s):
    return html.escape(s, quote=True)


# ---------- generated blocks ----------

def block_town_names():
    """Book: the town list as one attribute value, for its town check."""
    towns = json.loads(read(DATA, 'towns.json'))['towns']
    return esc('|'.join('%s, %s' % (t['name'], t['abbr']) for t in towns))


def block_town_chips():
    """Home: the town names as link chips, alphabetical within each state (copy.md). Names only; the price lives in the band above."""
    towns = json.loads(read(DATA, 'towns.json'))['towns']
    rows = []
    for state in ('Massachusetts', 'New Hampshire'):
        for t in sorted((t for t in towns if t['state'] == state), key=lambda t: t['name']):
            rows.append('        <li><a class="a-chip" href="service-area/%s.html">%s</a></li>' % (esc(t['slug']), esc(t['name'])))
    return '\n'.join(rows)


def block_town_near():
    """A town page's three nearest towns on the list, by public map position (copy.md's table is this sum, checked). It redoes itself when the real list arrives."""
    towns = json.loads(read(DATA, 'towns.json'))['towns']
    me = CURRENT_TOWN
    near = sorted((t for t in towns if t is not me and t['slug'] != me['slug']), key=lambda t: ((t['lon'] - me['lon']) * .734) ** 2 + (t['lat'] - me['lat']) ** 2)[:3]
    return '\n'.join('      <li><a class="a-chip -light" href="service-area/%s.html">%s</a></li>' % (esc(t['slug']), esc(t['name'])) for t in near)


def quote_foot(r):
    """Who wrote it. A sample has initials and "Sample review". A real review fills the other slots too: source (Facebook), date and a link to its post (copy.md, Held lines)."""
    source = ', '.join(x for x in (r.get('source'), r.get('date')) if x)
    link = ''
    if r.get('url'):
        link = ('\n        <a class="a-link" href="%s" target="_blank" rel="noopener"><span class="a-link__text">Read on Facebook</span><span class="sr-only"> (opens in a new tab)</span><svg class="a-link__arrow" aria-hidden="true"><use href="#i-arrow"/></svg></a>'
                % esc(r['url']))
    return (
        '      <figcaption class="m-quote__foot">\n'
        '        <span class="m-quote__who"><span class="m-quote__avatar" aria-hidden="true">%s</span><span><span class="m-quote__name">%s</span>%s</span></span>%s\n'
        '      </figcaption>' % (esc(r['initials']), esc(r['who']), ' <span class="m-quote__source">%s</span>' % esc(source) if source else '', link))


