def truck_part(name):
    """A generated fragment from tools/build_trucks.py."""
    return read(SRC, 'partials', 'trucks', name + '.html').strip('\n')


def block_review_grid():
    """Reviews: quotes mixed with photos, in reading order, from data/reviews.json. A photo is never inside a card, so none reads as the job a review is about (copy.md). Photos come out as picture tags, which expand() fills in next."""
    data = json.loads(read(DATA, 'reviews.json'))
    cols = {}
    for item in data['reviews_page']:
        rows = cols.setdefault(item['col'], [])
        if 'photo' in item:
            # sizes: from 641 a photo fills what its cards leave, by cover, so it can show wider than its column
            rows.append('    <div class="o-reviewGrid__photo%s a-inview">{{picture name="%s" class="o-reviewGrid__img" alt="%s" sizes="(min-width: 1025px) 46vw, (min-width: 641px) 80vw, 100vw"}}</div>' % (' -lead' if item.get('lead') else '', item['photo'], item['alt']))
        else:
            art = ''
            if item.get('art'):
                w, h = re.search(r'viewBox="\S+ \S+ (\S+) (\S+)"', read(ROOT, 'assets', 'trucks', item['art'] + '.svg')).groups()
                art = ('      <div class="m-seatCard__art" aria-hidden="true"><img class="m-quote__item -%s" src="assets/trucks/%s.svg" width="%s" height="%s" alt="" loading="lazy" decoding="async"></div>\n'
                       % (item['art'], item['art'], w, h))
            rows.append(
                '    <figure class="m-quote -card%s%s a-inview">\n'
                '%s'
                '      <blockquote class="m-quote__text"><p>&ldquo;%s&rdquo;</p></blockquote>\n'
                '%s\n'
                '    </figure>' % (' -soft' if item.get('tone') == 'soft' else '', ' m-seatCard' if art else '', art, esc(item['quote']), quote_foot(item)))
    flip = {i['col'] for i in data['reviews_page'] if i.get('lead')}
    return '\n'.join('   <div class="o-reviewGrid__col%s">\n%s\n   </div>' % (' -flip' if c in flip else '', '\n'.join(cols[c])) for c in sorted(cols))


