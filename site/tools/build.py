"""Quick Haul: page build.

Assembles every page as head + header + body + footer from src/partials/ and src/pages/<slug>.body.html,
fills the head slots from each page's meta comment, pulls generated blocks ({{> name}}) from data/*.json,
writes <picture> markup ({{picture ...}}) from data/image-manifest.json (run tools/images.py first), and
writes sitemap.xml and robots.txt. Town pages come from one template (src/templates/town.body.html) and
data/towns.json, one folder down at service-area/<slug>.html. Standard library only.

Usage (from the site folder):
  python tools/build.py           build every page
  python tools/build.py --check   fail (exit 1) if any built file is stale; writes nothing
"""
