def block_price_sum(load, extra=None):
    """Pricing's worked examples: the only sums on the site. Read from data/prices.json, so a total can't disagree with its parts."""
    data = json.loads(read(DATA, 'prices.json'))
    card = next(c for c in data['cards'] if c['value'] == load)
    rows = [(card['label'], '$%d' % card['price'])]
    total = card['price']
    if extra:
        rows.append((extra, '$%d' % data['fridge_fee']))
        total += data['fridge_fee']
    else:
        rows.append(('Extras', 'None'))
    cells = ''.join('<div class="m-sum__row"><dt>%s</dt><dd class="a-num">%s</dd></div>' % (esc(a), esc(b)) for a, b in rows)
    return '<dl class="m-sum">%s<div class="m-sum__row -total"><dt>Total</dt><dd>$%d</dd></div></dl>' % (cells, total)


