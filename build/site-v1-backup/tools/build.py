def read(*parts):
    path = os.path.join(*parts)
    if not os.path.exists(path):
        sys.exit('Missing file: ' + os.path.relpath(path, ROOT))
    with open(path, encoding='utf-8') as fh:
        return fh.read()


def esc(s):
    return html.escape(s, quote=True)


