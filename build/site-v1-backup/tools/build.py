# Map window, in degrees. The frame is square, so the latitude span is the longitude span at 42.75N (cos = .734).
# Cropped to the towns (was -71.62 to -70.98, critic r1: empty corners, crowded at 390): 18% more room between the dots.
MAP_W, MAP_E, MAP_N = -71.56, -71.02, 42.94
MAP_S = MAP_N - (MAP_E - MAP_W) * .734
# Which side of the dot each label sits on, so no name crosses the state line (critic r1) and close neighbours read apart.
# Right is the default. Salem goes left and Methuen right because each sits just inside the line on that side.
MAP_LEFT = {'Dracut', 'Lowell', 'Nashua', 'Pelham', 'Salem', 'Haverhill'}   # Dracut: on its right, the river touched the T (critic, Contact r1). Londonderry: on its left, the river ran through the name
# The state line, roughly, as a drawing rather than survey data.
MAP_BORDER = [(-71.62, 42.70), (-71.30, 42.70), (-71.25, 42.73), (-71.18, 42.795), (-71.13, 42.835), (-71.03, 42.875), (-70.98, 42.89)]
# The Merrimack, roughly, unlabelled: public geography that ties the towns together, drawn rather than surveyed (critic r2: the map carried too little for its size).
# It passes under Lawrence and its label and turns up east of them: through the town it ran over the dot and into the L (critic, Contact r1). Less true to the river there, and it's only ever a drawing.
MAP_RIVER = [(-71.46, 43.0), (-71.47, 42.85), (-71.46, 42.77), (-71.425, 42.677), (-71.35, 42.645), (-71.31, 42.648), (-71.26, 42.66), (-71.1618, 42.682), (-71.0875, 42.687), (-71.0348, 42.697), (-71.0225, 42.742), (-70.98, 42.78)]
# 56 units is 46px at 1440, where the town pages draw the map 658 wide. Lawrence sits 39 units under Methuen, so their hit areas are shifted to meet instead of overlap (critic r2).
MAP_HIT_SHIFT = {'Methuen': -9, 'Lawrence': 9}
# Haverhill in the heavy weight, on its own page at 390, reaches the state line unless it sits a little under its dot. Phones only, in the CSS: level with its dot from 641 up, where it has the room (critic, Contact r1: 7px high at 1440).
MAP_LABEL_DROP = {'Haverhill'}
MAP_ARM = 44   # registration arm, in map units: 42px at 1440, 18px at 390


def map_xy(lon, lat):
    return (lon - MAP_W) / (MAP_E - MAP_W) * 800, (MAP_N - lat) / (MAP_N - MAP_S) * 800


def map_smooth(points):
    """A soft line through the points' midpoints, so the river doesn't read as a second faceted border."""
    p = [map_xy(*q) for q in points]
    d = 'M%.1f %.1f' % p[0]
    for i in range(1, len(p) - 1):
        d += 'Q%.1f %.1f %.1f %.1f' % (p[i][0], p[i][1], (p[i][0] + p[i + 1][0]) / 2, (p[i][1] + p[i + 1][1]) / 2)
    return d + 'L%.1f %.1f' % p[-1]


def map_arms(me, spots):
    """The marked town's registration arms. No arm on the label's side, and each stops 8 units short of any other town's
    dot or label, which is sized here at its phone width, the widest it gets. An arm under 14 units is left out."""
    x, y = me['x'], me['y']
    boxes = []
    for s in spots:
        if s is me:
            continue
        boxes.append((s['x'] - 7, s['y'] - 7, s['x'] + 7, s['y'] + 7))
        wide = len(s['name']) * 19
        if s['left']:
            boxes.append((s['x'] - 14 - wide, s['y'] - 18, s['x'] - 14, s['y'] + 10))
        else:
            boxes.append((s['x'] + 14, s['y'] - 18, s['x'] + 14 + wide, s['y'] + 10))
    arms = []
    for dx, dy in ((1, 0), (-1, 0), (0, -1), (0, 1)):
        if dy == 0 and (dx < 0) == me['left']:
            continue
        reach = MAP_ARM
        for l, t, r, u in boxes:
            if dx and t - 2 < y < u + 2:
                gap = (l - x) if dx > 0 else (x - r)
            elif dy and l - 2 < x < r + 2:
                gap = (t - y) if dy > 0 else (y - u)
            else:
                continue
            if gap > 0:
                reach = min(reach, gap - 18)   # 10 from the dot's edge to the arm's start, 8 clear at the far end
        if reach >= 14:
            arms.append('M%.1f %.1f%s%d' % (x + dx * 10, y + dy * 10, 'h' if dx else 'v', (dx or dy) * reach))
    return ''.join(arms)


def block_town_map():
    """Our own drawing of the service area: the state line, the river, the 12 placeholder towns from data/towns.json placed
    by latitude and longitude. No third-party map: the brief's Google Map needs the real base town (content/placeholders.md).
    On a town page that town is the marked one, inside a registration mark (critic r1: no sense of place).
    The links are for the mouse only (tabindex -1, under role="img"); the same towns are real links in the hub's list."""
    data = json.loads(read(DATA, 'towns.json'))
    border = ' '.join('%.1f,%.1f' % map_xy(*p) for p in MAP_BORDER)
    north = 'M0 0H800V%.1fL%s Z' % (map_xy(*MAP_BORDER[-1])[1], ' '.join('%.1f %.1f' % map_xy(*p) for p in reversed(MAP_BORDER)))
    spots = []
    for t in data['towns']:
        x, y = map_xy(t['lon'], t['lat'])
        spots.append({'town': t, 'name': t['name'], 'x': x, 'y': y, 'left': t['name'] in MAP_LEFT})
    places, reg = [], ''
    for s in spots:
        t, name, x, y = s['town'], s['name'], s['x'], s['y']
        wide = len(name) * 15   # the label's width at the desktop size, near enough for a hit area
        top = y - 28 + MAP_HIT_SHIFT.get(name, 0)
        if s['left']:
            tx, anchor = x - 14, ' text-anchor="end"'
            hit = (x - 14 - wide, top, wide + 21, 56)
        else:
            tx, anchor = x + 14, ''
            hit = (x - 7, top, wide + 21, 56)
        mark = '<rect class="m-map__dot" x="%.1f" y="%.1f" width="10" height="10"/><text class="m-map__town%s" x="%.1f" y="%.1f"%s>%s</text>' % (x - 5, y - 5, ' -drop' if name in MAP_LABEL_DROP else '', tx, y + 6, anchor, esc(name))
        if CURRENT_TOWN and CURRENT_TOWN['slug'] == t['slug']:
            reg = '      <path class="m-map__reg" d="%s"/>\n' % map_arms(s, spots)
            places.append('      <g class="m-map__place -here">%s</g>' % mark)
        else:
            places.append(
                '      <a class="m-map__place m-map__link" href="service-area/%s.html" tabindex="-1" data-place="%s"><rect class="m-map__hit" x="%.1f" y="%.1f" width="%d" height="%d"/>%s</a>'
                % (esc(t['slug']), esc(t['slug']), hit[0], hit[1], hit[2], hit[3], mark))
    # the marked town paints last, so its label is never under a neighbour's edge
    places.sort(key=lambda p: '-here' in p)
    return (
        '<svg class="m-map" viewBox="0 0 800 800" role="img" aria-label="Map of the towns Quick Haul covers in Massachusetts and New Hampshire" focusable="false">\n'
        '      <defs><pattern id="qh-map-dots" width="11" height="11" patternUnits="userSpaceOnUse"><circle class="m-map__halftone" cx="2.75" cy="2.75" r="1"/><circle class="m-map__halftone" cx="8.25" cy="8.25" r="1"/></pattern></defs>\n'
        '      <path class="m-map__north" fill="url(#qh-map-dots)" d="%s"/>\n'
        '      <path class="m-map__river" d="%s"/>\n'
        '      <polyline class="m-map__border" points="%s"/>\n'
        '%s'
        '      <text class="m-map__state" x="164" y="52">New Hampshire</text>\n'   # right of the river, which ran through it at x 28 (critic, Contact r2)
        '      <text class="m-map__state" x="28" y="772">Massachusetts</text>\n'
        '%s\n'
        '    </svg>' % (north, map_smooth(MAP_RIVER), border, reg, '\n'.join(places)))


def block_ticket():
    """The work order. One copy of the markup for the homepage and the town pages; a town page gets its town filled in."""
    t = read(SRC, 'partials', 'ticket.html').replace('{{> town-options}}', block_town_options()).strip('\n')
    if CURRENT_TOWN:
        label = '%s, %s' % (CURRENT_TOWN['name'], CURRENT_TOWN['abbr'])
        t = t.replace('data-ticket-town>', 'value="%s" data-ticket-town>' % esc(label))
        default = 'Start typing to check we come to you'
        t = t.replace('data-ticket-note data-error', 'data-ticket-note data-default="%s" data-error' % default)
        t = t.replace('>%s</p>' % default, '>Yes, we come to %s.</p>' % esc(label))
        # no halftone here: the band after this ticket is cream too, so it only read as a heavy bar (critic, Service area r1)
        t = t.replace('<div class="a-halftone" aria-hidden="true"></div>', '')
    return t


def banner_art(mode='static'):
    t = read(SRC, 'partials', 'banner-art.html').strip('\n')
    if mode == 'empty':
        t = re.sub(r'<!-- load:start -->.*?<!-- load:end -->\n?', '', t, flags=re.S)
    if mode == 'donate':
        # the same truck, with room on its left for the dresser and bike: 276 more units of ground line
        t = t.replace('viewBox="0 0 720 330"', 'viewBox="-276 0 996 330"').replace('d="M0 316H720"', 'd="M-276 316H720"')
        t = t.replace('      <!-- load:start -->', read(SRC, 'partials', 'banner-art-items.html').rstrip('\n') + '\n      <!-- load:start -->')
    if mode == 'plain':
        # no drawing: the spec's plain text header, for a page to read
        t = re.sub(r'  <div class="m-banner__art".*?</svg>\n  </div>\n', '', t, flags=re.S)
    if mode == 'commercial':
        # the same banner parts around a different drawing: a row of properties with the truck beside them
        t = re.sub(r'<svg class="m-truck".*?</svg>', lambda m: read(SRC, 'partials', 'commercial-art.html').strip(), t, flags=re.S)
    if mode == 'live':
        t = t.replace('data-banner-truck', 'data-truck')   # the town ticket's load chips fill this bed, as on the homepage
    else:
        t = t.replace(' data-banner-truck', '')
    return t


