def parse_meta(src, page):
    m = re.match(r'\s*<!--\s*meta\s*\n(.*?)-->\s*\n', src, re.S)
    if not m:
        sys.exit('%s: the body must open with a <!-- meta ... --> comment' % page)
    meta = {}
    for line in m.group(1).strip().splitlines():
        if ':' in line:
            k, v = line.split(':', 1)
            meta[k.strip()] = v.strip()
    for need in ('title', 'schema'):
        if not meta.get(need):
            sys.exit('%s: meta is missing %s' % (page, need))
    if not meta.get('description') and meta.get('robots') != 'noindex':   # 404: copy.md gives it no description
        sys.exit('%s: meta is missing description' % page)
    return meta, src[m.end():]


def page_url(slug):
    return SITE_URL + ('/' if slug == 'index' else '/' + slug + '.html')


def fill_head(head, meta, slug, source):
    desc = (PREVIEW_PREFIX if PREVIEW else '') + meta['description'] if meta.get('description') else ''
    schema = read(SRC, 'schema', meta['schema']).strip().replace('{{SITE_URL}}', SITE_URL)
    schema = schema.replace('{{PAGE_URL}}', page_url(slug)).replace('{{PAGE_TITLE}}', meta['title'])
    if '{{FAQ_ENTITIES}}' in schema:
        schema = schema.replace('{{FAQ_ENTITIES}}', faq_entities())
    if CURRENT_TOWN:
        schema = schema.replace('{{TOWN}}', CURRENT_TOWN['name']).replace('{{ABBR}}', CURRENT_TOWN['abbr']).replace('{{STATE}}', CURRENT_TOWN['state'])
    preloads = []
    for p in filter(None, [x.strip() for x in meta.get('preload', '').split(',')]):
        kind = 'font' if p.endswith(('.woff2', '.otf')) else 'image'
        if kind == 'font':
            ftype = 'font/woff2' if p.endswith('.woff2') else 'font/otf'
            preloads.append('<link rel="preload" href="%s" as="font" type="%s" crossorigin>' % (p, ftype))
        else:
            preloads.append('<link rel="preload" href="%s" as="image" fetchpriority="high">' % p)
    slots = {
        'TITLE': esc(meta['title']),
        'DESCRIPTION': esc(desc),
        'CANONICAL': page_url(slug),
        'ROBOTS': 'noindex' if PREVIEW or meta.get('robots') == 'noindex' else '',
        'OG_TITLE': esc(meta.get('og_title') or meta['title']),
        'OG_DESCRIPTION': esc((PREVIEW_PREFIX if PREVIEW else '') + (meta.get('og_description') or meta.get('description', ''))),
        'OG_IMAGE': SITE_URL + '/' + meta['og_image'] if meta.get('og_image') else '',
        'OG_IMAGE_ALT': esc(meta.get('og_image_alt', '')),
        'URL': page_url(slug),
        'PRELOAD': '\n'.join(preloads),
        'SCHEMA': schema,
        'GENERATED': GENERATED_NOTE % source,
    }
    out = []
    for line in head.splitlines():
        tags = re.findall(r'\{\{([A-Z_]+)\}\}', line)
        if tags and any(not slots.get(t) for t in tags):
            continue   # drop any slot a page leaves empty
        for t in tags:
            line = line.replace('{{%s}}' % t, slots[t])
        out.append(line)
    return '\n'.join(out)


def prefix_paths(doc, prefix):
    """Pages below the site root reach assets and other pages through a prefix: ../ for the town pages, / for the 404
    (a host serves it at whatever URL was asked for, so a relative path would break one folder down). Only attributes
    written relative to the root change; anchors, tel:, mailto: and full URLs stay as they are."""
    def one(m):
        return '%s="%s%s"' % (m.group(1), prefix, m.group(2))
    doc = re.sub(r'\b(href|src|action)="(?!https?:|tel:|mailto:|data:|#|/)([^"]+)"', one, doc)

    def many(m):
        return 'srcset="%s"' % ', '.join(prefix + c.strip() for c in m.group(1).split(','))
    return re.sub(r'\bsrcset="([^"]+)"', many, doc)


def build_page(slug, raw, source, parts):
    page = source
    meta, body = parse_meta(raw, page)
    head = fill_head(parts['head'], meta, slug, source)
    header = parts['header']
    if not PREVIEW:
        header = re.sub(r'<!-- preview:start -->.*?<!-- preview:end -->\n?', '', header, flags=re.S)
    footer = parts['footer']
    if meta.get('estimate') == 'no':
        footer = re.sub(r'<!-- estimate:start -->.*?<!-- estimate:end -->\n?', '', footer, flags=re.S)
        footer = footer.replace('a-halftone -dark', 'a-halftone -toInk')   # no slate band above it: the dots come off the cream
    body = expand(body, page)
    header = expand(header, 'src/partials/header.html')
    footer = expand(footer, 'src/partials/footer.html')
    doc = head.replace('{{GENERATED}}', GENERATED_NOTE % source)
    doc = '%s\n<body>\n%s\n<main id="main">\n%s\n</main>\n%s\n</body>\n</html>\n' % (doc, header.strip(), body.strip(), footer.strip())
    if slug == '404':
        doc = prefix_paths(doc, '/')
    elif '/' in slug:
        doc = prefix_paths(doc, '../')
    return doc


def main():
    global CURRENT_TOWN
    check = '--check' in sys.argv
    parts = {k: read(SRC, 'partials', k + '.html') for k in ('head', 'header', 'footer')}
    slugs = sorted(f[:-len('.body.html')] for f in os.listdir(os.path.join(SRC, 'pages')) if f.endswith('.body.html'))
    outputs = {}
    for slug in slugs:
        outputs[slug + '.html'] = build_page(slug, read(SRC, 'pages', slug + '.body.html'), 'src/pages/%s.body.html' % slug, parts)
    # town pages: one template, only the town, state and abbreviation change (copy.md)
    town_slugs = []
    if os.path.exists(os.path.join(SRC, 'templates', 'town.body.html')):
        template = read(SRC, 'templates', 'town.body.html')
        for t in json.loads(read(DATA, 'towns.json'))['towns']:
            CURRENT_TOWN = t
            label = '%s, %s' % (t['name'], t['abbr'])
            raw = template.replace('{{TOWN_QUERY}}', quote_plus(label)).replace('{{TOWN}}', t['name']).replace('{{ABBR}}', t['abbr']).replace('{{STATE}}', t['state'])
            slug = 'service-area/' + t['slug']
            town_slugs.append(slug)
            outputs[slug + '.html'] = build_page(slug, raw, 'src/templates/town.body.html and data/towns.json', parts)
        CURRENT_TOWN = None
    urls = '\n'.join('  <url><loc>%s</loc></url>' % page_url(s) for s in slugs + town_slugs if s != '404')
    outputs['sitemap.xml'] = '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n%s\n</urlset>\n' % urls
    if PREVIEW:
        outputs['robots.txt'] = '# Design preview: not for search engines yet. tools/build.py PREVIEW = False at launch.\nUser-agent: *\nDisallow: /\n'
    else:
        outputs['robots.txt'] = 'User-agent: *\nAllow: /\nSitemap: %s/sitemap.xml\n' % SITE_URL
    stale = []
    for name, text in outputs.items():
        path = os.path.join(ROOT, name)
        current = open(path, encoding='utf-8', newline='').read() if os.path.exists(path) else None
        if current != text:
            stale.append(name)
            if not check:
                os.makedirs(os.path.dirname(path), exist_ok=True)
                with open(path, 'w', encoding='utf-8', newline='\n') as fh:
                    fh.write(text)
    if check:
        if stale:
            sys.exit('Stale: ' + ', '.join(stale) + '. Run python tools/build.py')
        print('Up to date: %d files' % len(outputs))
    else:
        print('Built: ' + (', '.join(stale) if stale else 'nothing changed'))


if __name__ == '__main__':
    main()
