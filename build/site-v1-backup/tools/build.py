_manifest = None


def manifest():
    global _manifest
    if _manifest is None:
        _manifest = json.loads(read(DATA, 'image-manifest.json'))
    return _manifest


def picture(attrs, page):
    name = attrs.get('name')
    m = manifest().get(name)
    if not m:
        sys.exit('%s: no image "%s" in data/image-manifest.json (run tools/images.py)' % (page, name))
    if 'alt' not in attrs:
        sys.exit('%s: picture "%s" has no alt (use alt="" for decorative images)' % (page, name))
    if 'sizes' not in attrs:
        sys.exit('%s: picture "%s" has no sizes' % (page, name))
    srcset = ', '.join('%s %dw' % (w['file'], w['w']) for w in m['webp'])
    fb = m['fallback']
    eager = 'eager' in attrs
    img = '<img class="%s" src="%s" width="%d" height="%d" alt="%s"%s decoding="async">' % (
        esc(attrs.get('class', 'b-photo__img')), fb['file'], fb['w'], fb['h'], esc(attrs['alt']),
        ' fetchpriority="high"' if eager else ' loading="lazy"')
    return '<picture><source type="image/webp" srcset="%s" sizes="%s">%s</picture>' % (srcset, esc(attrs['sizes']), img)


ATTR_RE = re.compile(r'(\w+)(?:="([^"]*)")?')


def expand(body, page):
    def inc(m):
        name = m.group(1)
        if name not in BLOCKS:
            sys.exit('%s: unknown block {{> %s}}' % (page, name))
        return BLOCKS[name]()
    body = re.sub(r'\{\{>\s*([\w-]+)\s*\}\}', inc, body)

    def pic(m):
        attrs = {k: (v if v is not None else True) for k, v in ATTR_RE.findall(m.group(1))}
        return picture(attrs, page)
    body = re.sub(r'\{\{picture\s+(.*?)\}\}', pic, body, flags=re.S)
    if '{{' in body:
        sys.exit('%s: unexpanded {{ }} tag left in the body' % page)
    return body


